"""Keep wiki/log.md short enough for an agent to read in one go, by moving its oldest entries to archive files.

The log is append-only and grows with every operation; in the MEA review repository, at about 290 kB, it took several reads to get
through, and an agent starting a session reads it for context. When log.md is larger than --limit bytes, the oldest
entries are moved, unchanged and in their original order, until what stays is at most --keep bytes. The moved
entries are written to archive files of at most --chunk bytes each, named by the dates they span
in wiki/log-archive/ (wiki/log-archive/log-2026-11-01-to-2026-11-09.md), so every archive can also be read in one go. The list of archives in the
header of log.md, between the two `archives` comment lines, is rewritten on every run.

The gap between --limit and --keep is deliberate: after a rotation the log has room to grow again, so the script is
not needed after every entry. scripts/check.py warns when log.md passes the limit; keep LOG_LIMIT there in step.

Usage (run from the repository root):
    python -I scripts/rotate_log.py            dry run: says what would move where, writes nothing
    python -I scripts/rotate_log.py --write    move the entries and update the archive list
Options: --limit 40000 --keep 20000 --chunk 40000 (bytes of UTF-8).
"""
import argparse
import re
import sys
from datetime import date
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

WIKI = Path("wiki")
LOG = WIKI / "log.md"
ARCHIVE_DIR = WIKI / "log-archive"  # its own folder, so the archives do not crowd the concept pages in wiki/
ENTRY = re.compile(r"^## \[(\d{4}-\d{2}-\d{2})\] ")
ARCHIVE_NAME = re.compile(r"^log-(\d{4}-\d{2}-\d{2})-to-(\d{4}-\d{2}-\d{2})(?:-(\d+))?\.md$")


def archive_order(name):
    """Sort key for archive names: by the dates, then by the -2, -3 ... suffix that archive_path adds when one
    span of dates needs more than one file. Plain string order would put "-2.md" before ".md" and "-10" before
    "-2", because "-" sorts before "." and digits sort as text."""
    m = ARCHIVE_NAME.match(name)
    return m.group(1), m.group(2), int(m.group(3) or 1)
BEGIN, END = "<!-- archives: generated by scripts/rotate_log.py -->", "<!-- /archives -->"


def size(text):
    return len(text.encode("utf-8"))


def split_log(text):
    """(header, [entry text]) — an entry runs from its `## [date]` line to the next one."""
    lines = text.split("\n")
    starts = [i for i, line in enumerate(lines) if ENTRY.match(line)]
    if not starts:
        return text, []
    header = "\n".join(lines[:starts[0]])
    entries = ["\n".join(lines[a:b]).rstrip("\n") for a, b in zip(starts, starts[1:] + [len(lines)])]
    return header, entries


def chunks(entries, limit):
    out, current = [], []
    for entry in entries:
        if current and size("\n\n".join(current + [entry])) > limit:
            out.append(current)
            current = []
        current.append(entry)
    if current:
        out.append(current)
    return out


def archive_path(group, taken):
    dates = [ENTRY.match(e).group(1) for e in group]
    stem = f"log-{min(dates)}-to-{max(dates)}"
    path, n = ARCHIVE_DIR / f"{stem}.md", 2
    while path.exists() or path in taken:
        path, n = ARCHIVE_DIR / f"{stem}-{n}.md", n + 1
    return path


def archive_text(path, group):
    m = ARCHIVE_NAME.match(path.name)
    return (f"# Wiki Log, {m.group(1)} to {m.group(2)}\n\n"
            f"Entries moved from [log.md](../log.md) by `scripts/rotate_log.py` on {date.today().isoformat()}, unchanged "
            f"and in their original order (the entries before 2026-07 are not in date order; that is how they were "
            f"written). New entries go to [log.md](../log.md).\n\n---\n\n" + "\n\n".join(group) + "\n")


def with_archive_list(header, names):
    listing = "\n".join([BEGIN] + [f"- [{n}]({ARCHIVE_DIR.name}/{n})" for n in names] + [END])
    if BEGIN in header:
        return re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda _: listing, header, flags=re.S)
    return header.replace("\nFormat:", f"\nOlder entries are in these archive files, oldest first:\n\n{listing}\n\nFormat:", 1)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--write", action="store_true", help="move the entries (default: dry run)")
    parser.add_argument("--limit", type=int, default=40_000, help="rotate when log.md is larger than this")
    parser.add_argument("--keep", type=int, default=20_000, help="what stays in log.md after a rotation, at most")
    parser.add_argument("--chunk", type=int, default=40_000, help="largest archive file")
    args = parser.parse_args()

    text = LOG.read_text(encoding="utf-8")
    if "\x00" in text:
        sys.exit("log.md contains a NUL byte, which makes grep treat it as binary; fix it first")
    header, entries = split_log(text)
    existing = sorted((p.name for p in ARCHIVE_DIR.glob("log-*.md") if ARCHIVE_NAME.match(p.name)), key=archive_order)
    print(f"log.md: {size(text)} bytes, {len(entries)} entries; limit {args.limit}, keep {args.keep}")
    if size(text) <= args.limit:
        print("nothing to do")
        if args.write and existing:
            LOG.write_text(with_archive_list(header, existing).rstrip("\n") + "\n\n" + "\n\n".join(entries) + "\n",
                           encoding="utf-8", newline="\n")
        return
    kept = list(entries)
    moved = []
    while len(kept) > 1 and size(header) + size("\n\n".join(kept)) > args.keep:
        moved.append(kept.pop(0))
    taken, plan = set(), []
    for group in chunks(moved, args.chunk):
        path = archive_path(group, taken)
        taken.add(path)
        plan.append((path, group))
        print(f"  {len(group):3} entries, {size(chr(10).join(group)):6} bytes -> {path.as_posix()}")
    print(f"log.md keeps {len(kept)} entries")
    if not args.write:
        print("dry run: nothing written")
        return
    ARCHIVE_DIR.mkdir(exist_ok=True)
    for path, group in plan:
        path.write_text(archive_text(path, group), encoding="utf-8", newline="\n")
    names = existing + [p.name for p, _ in plan]
    LOG.write_text(with_archive_list(header, names).rstrip("\n") + "\n\n" + "\n\n".join(kept) + "\n",
                   encoding="utf-8", newline="\n")
    print(f"wrote {len(plan)} archive file(s) and log.md")


if __name__ == "__main__":
    main()
